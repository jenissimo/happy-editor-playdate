import type { Scene } from './types.js'

/** Stable JSON for clipboard / file export. */
export function exportSceneJson(scene: Scene): string {
  return `${JSON.stringify(scene, null, 2)}\n`
}

/** Lua table dump — readable enough for hand-edit, parseable by a tiny loader later. */
export function exportSceneLua(scene: Scene, globalName?: string): string {
  const name =
    globalName ??
    scene.name
      .replace(/(^|[_-])(\w)/g, (_: string, __: string, c: string) =>
        c.toUpperCase(),
      )
      .replace(/[^A-Za-z0-9_]/g, '') + 'Scene'

  return `-- Generated by HappyEditor — DO NOT EDIT
-- Screen: ${scene.name} (${scene.width}x${scene.height})
${name} = ${toLua(scene)}

return ${name}
`
}

function toLua(value: unknown, indent = 0): string {
  const pad = '  '.repeat(indent)
  const padIn = '  '.repeat(indent + 1)

  if (value === null || value === undefined) return 'nil'
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : '0'
  if (typeof value === 'string') return JSON.stringify(value)

  if (Array.isArray(value)) {
    if (value.length === 0) return '{}'
    const parts = value.map((v) => `${padIn}${toLua(v, indent + 1)}`)
    return `{\n${parts.join(',\n')}\n${pad}}`
  }

  if (typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>).filter(
      ([, v]) => v !== undefined,
    )
    if (entries.length === 0) return '{}'
    const parts = entries.map(([k, v]) => {
      const key = /^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : `[${JSON.stringify(k)}]`
      return `${padIn}${key} = ${toLua(v, indent + 1)}`
    })
    return `{\n${parts.join(',\n')}\n${pad}}`
  }

  return 'nil'
}
