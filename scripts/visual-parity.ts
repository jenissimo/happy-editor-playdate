/**
 * Visual parity: Playdate Simulator framebuffer vs editor canvas preview.
 *
 * Usage:
 *   bun scripts/visual-parity.ts                 # parity-kit
 *   bun scripts/visual-parity.ts parity-rotate
 *   bun scripts/visual-parity.ts --all           # menu + parity-*
 *
 * Requires PLAYDATE_SDK_PATH / pdc + Simulator.
 * Writes artifacts under .playdate-editor/visual/
 */
import { spawn, spawnSync } from 'node:child_process'
import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
  unlinkSync,
} from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL, fileURLToPath } from 'node:url'
import { createCanvas, loadImage, Image, ImageData } from '@napi-rs/canvas'
import {
  findPdc,
  findSimulator,
  PDX_OUT,
  writeActiveSceneLua,
} from '../src/core/playdate/sdk.ts'
import {
  ROOT,
  SOURCE_DIR,
  SCENES_DIR,
  listScenes,
  readSceneFile,
} from '../src/core/scene/io.ts'
import { indexPlaydateAssets } from '../src/core/assets/indexAssets.ts'
import {
  drawSceneToCanvas,
  clearSceneFontCache,
} from '../src/editor/render/drawSceneToCanvas.ts'
import {
  diffPngFiles,
  quantizePngTo1Bit,
} from '../src/editor/render/pixelDiff.ts'
import {
  clearPlaydateFontCache,
  setPlaydateFontHooks,
} from '../src/editor/fonts/playdateFont.ts'
import { SCREEN_H, SCREEN_W } from '../src/core/constants.ts'

const OUT_DIR = join(ROOT, '.playdate-editor', 'visual')
const CAPTURE_LUA = join(SOURCE_DIR, 'visual_capture.lua')
const arg = process.argv[2] ?? 'parity-kit'
const runAll = arg === '--all' || arg === 'all'

function writeCaptureLua(absPngPath: string | null) {
  const body =
    absPngPath == null
      ? `-- Generated by visual-parity — disabled\nVisualCapturePath = nil\n`
      : `-- Generated by visual-parity\nVisualCapturePath = ${JSON.stringify(absPngPath.replace(/\\/g, '/'))}\n`
  writeFileSync(CAPTURE_LUA, body)
}

function buildPdx(): void {
  const pdc = findPdc()
  if (!pdc) throw new Error('pdc not found')
  const r = spawnSync(pdc, ['--skip-unknown', SOURCE_DIR, PDX_OUT], {
    encoding: 'utf8',
    env: process.env,
  })
  if (r.status !== 0) {
    throw new Error(`pdc failed: ${r.stderr || r.stdout}`)
  }
}

async function renderPreviewPng(scenePath: string, outPng: string) {
  clearPlaydateFontCache()
  clearSceneFontCache()

  setPlaydateFontHooks({
    createCanvas: (w, h) => createCanvas(w, h) as unknown as {
      width: number
      height: number
      getContext: (id: '2d') => CanvasRenderingContext2D | null
    },
    loadAtlas: async (url) => {
      const path = url.startsWith('file:') ? fileURLToPath(url) : url
      return loadImage(path)
    },
    readFnt: async (url) => {
      const path = url.startsWith('file:') ? fileURLToPath(url) : url
      return readFileSync(path, 'utf8')
    },
  })

  const file = readSceneFile(scenePath)
  const assets = indexPlaydateAssets()
  const imageCache = new Map<string, Awaited<ReturnType<typeof loadImage>>>()

  const load = async (rel: string) => {
    const full = join(SOURCE_DIR, rel)
    if (imageCache.has(full)) return imageCache.get(full)!
    const img = await loadImage(full)
    imageCache.set(full, img)
    return img
  }

  for (const n of file.scene.nodes) {
    if (n.type === 'panel' || n.type === 'image') {
      const slice = assets.find(
        (a) => a.basePath === n.asset && a.kind === 'slice',
      )
      const image = assets.find(
        (a) =>
          a.basePath === n.asset &&
          (a.kind === 'image' || a.kind === 'table'),
      )
      const rel = slice?.relativePath ?? image?.relativePath
      if (rel) {
        try {
          await load(rel)
        } catch {
          /* missing */
        }
      }
    }
  }

  const origFetch = globalThis.fetch.bind(globalThis)
  globalThis.fetch = (async (input: RequestInfo | URL, init?: RequestInit) => {
    const url = String(input)
    if (url.startsWith('file:')) {
      const buf = readFileSync(fileURLToPath(url))
      return new Response(buf)
    }
    return origFetch(input, init)
  }) as typeof fetch

  ;(globalThis as unknown as { Image: typeof Image }).Image = Image
  ;(globalThis as unknown as { ImageData: typeof ImageData }).ImageData =
    ImageData

  const canvas = createCanvas(SCREEN_W, SCREEN_H)
  const ctx = canvas.getContext('2d')

  await drawSceneToCanvas(
    ctx as unknown as CanvasRenderingContext2D,
    file.scene,
    {
      list: assets,
      createCanvas: (w, h) =>
        createCanvas(w, h) as unknown as {
          width: number
          height: number
          getContext: (id: '2d') => CanvasRenderingContext2D | null
        },
      fontUrlFor: (rel) => pathToFileURL(join(SOURCE_DIR, rel)).href,
      getImage: (basePath) => {
        const slice = assets.find(
          (a) => a.basePath === basePath && a.kind === 'slice',
        )
        const image = assets.find(
          (a) =>
            a.basePath === basePath &&
            (a.kind === 'image' || a.kind === 'table'),
        )
        const rel = slice?.relativePath ?? image?.relativePath
        if (!rel) return null
        return imageCache.get(join(SOURCE_DIR, rel)) ?? null
      },
    },
  )

  mkdirSync(OUT_DIR, { recursive: true })
  writeFileSync(outPng, canvas.toBuffer('image/png'))
  globalThis.fetch = origFetch
}

function runSimulatorCapture(simPng: string): Promise<void> {
  const sim = findSimulator()
  if (!sim) return Promise.reject(new Error('PlaydateSimulator not found'))

  writeCaptureLua(simPng)
  buildPdx()

  return new Promise((resolve, reject) => {
    if (existsSync(simPng)) {
      try {
        unlinkSync(simPng)
      } catch {
        /* */
      }
    }
    const child = spawn(sim, [PDX_OUT], {
      stdio: 'ignore',
      windowsHide: false,
    })
    const started = Date.now()
    let settled = false
    const finish = (err?: Error) => {
      if (settled) return
      settled = true
      clearInterval(timer)
      try {
        child.kill()
      } catch {
        /* */
      }
      if (err) reject(err)
      else resolve()
    }
    const timer = setInterval(() => {
      if (existsSync(simPng) && Date.now() - started > 600) {
        setTimeout(() => finish(), 500)
      } else if (Date.now() - started > 45000) {
        finish(new Error('Simulator capture timed out'))
      }
    }, 200)
    child.on('exit', () => {
      if (existsSync(simPng)) finish()
      else if (Date.now() - started > 1500) {
        finish(new Error('Simulator exited without writing capture'))
      }
    })
  })
}

async function runOneScene(sceneName: string): Promise<boolean> {
  const scenes = listScenes()
  const file =
    scenes.find((s) => s.name === sceneName) ??
    (existsSync(join(SCENES_DIR, `${sceneName}.scene.json`))
      ? readSceneFile(join(SCENES_DIR, `${sceneName}.scene.json`))
      : null)
  if (!file) {
    console.error(`Scene not found: ${sceneName}`)
    return false
  }

  console.log(`\nVisual parity · scene="${file.name}"`)
  writeActiveSceneLua(file.scene)

  const previewRaw = join(OUT_DIR, `${file.name}-preview.png`)
  const simRaw = join(OUT_DIR, `${file.name}-sim.png`)
  const preview1 = join(OUT_DIR, `${file.name}-preview-1bit.png`)
  const sim1 = join(OUT_DIR, `${file.name}-sim-1bit.png`)
  const diffOut = join(OUT_DIR, `${file.name}-diff.png`)

  console.log('Rendering editor canvas…')
  await renderPreviewPng(file.path, previewRaw)
  quantizePngTo1Bit(previewRaw, preview1)

  console.log('Capturing Playdate Simulator…')
  try {
    await runSimulatorCapture(simRaw)
  } finally {
    writeCaptureLua(null)
    try {
      buildPdx()
    } catch {
      /* best-effort restore */
    }
  }

  if (!existsSync(simRaw)) {
    console.error('No simulator PNG written:', simRaw)
    return false
  }
  quantizePngTo1Bit(simRaw, sim1)

  const result = diffPngFiles(preview1, sim1, { diffOut, threshold: 0 })
  console.log(
    result.equal
      ? `PASS · ${result.width}×${result.height} identical`
      : `FAIL · ${result.mismatched}/${result.total} pixels differ (maxΔ=${result.maxChannelDelta})`,
  )
  if (!result.equal) console.log('diff:', diffOut)
  return result.equal
}

async function main() {
  mkdirSync(OUT_DIR, { recursive: true })
  const names = runAll
    ? listScenes()
        .map((s) => s.name)
        .filter((n) => n === 'menu' || n.startsWith('parity-'))
        .sort()
    : [arg]

  if (names.length === 0) {
    console.error('No scenes to test')
    process.exit(1)
  }

  console.log(`Visual parity suite · ${names.join(', ')}`)
  console.log('artifacts:', OUT_DIR)

  let failed = 0
  for (const name of names) {
    const ok = await runOneScene(name)
    if (!ok) failed++
  }

  console.log(
    failed === 0
      ? `\nALL PASS · ${names.length} scene(s)`
      : `\n${failed}/${names.length} scene(s) FAILED`,
  )
  if (failed) process.exit(1)
}

main().catch((e) => {
  console.error(e)
  writeCaptureLua(null)
  process.exit(1)
})
